"""Evaluate Dino's 92 joints against independently evaluated Blender world positions.

python -m tools.evaluate_dino_full_body TRUTH_JOINTS.json RIG_INFO.json OUT_DIR \
    --variant baseline=motion_baseline.json \
    --variant p1_guarded=motion_p1_guarded.json \
    --variant p2_error_weighted=motion_p2_weighted.json

TRUTH_JOINTS.json is generated by blender/apply_motion.py via evaluated
Blender pose bones, NOT by the solver under evaluation. Every variant
must match exact joint names/order, rig bones, FPS, and number of frames.
Refuse incomplete/mismatched inputs and overwrite; do NOT silently truncate.
These controlled synthetic sequences test rig reconstruction, not natural
Dino motion quality or real-video generalization.
"""
import argparse
import csv
import hashlib
import json
import pathlib

import numpy as np

PROFILE = "anymove.dino_full_body_blender_ground_truth/1"
GROUPS = (
    "head_neck", "torso_root", "forelimbs", "hindlimbs", "feet_toes",
    "tail", "unclassified",
)


def classify_joint(name):
    """Conservative semantic groups based on imported Dino joint names.

    Unknown names always remain visible in 'unclassified', never discarded.
    A per-joint explicit mapping can be supplied if imported names differ.
    """
    # Imported Dino keypoint names look like "joint:BoneName:tail".
    # The final ":tail" denotes the *END OF A BONE*, not Tail anatomy.
    # Never classify every bone-tail keypoint as an anatomical Dino tail!
    text = str(name).lower()
    parts = text.split(":")
    n = ":".join(parts[1:-1]) if (
        len(parts) >= 3 and parts[0] == "joint" and
        parts[-1] in ("head", "tail")) else text
    if "tail" in n:
        return "tail"
    if any(w in n for w in (
        "toe", "foot", "paw", "ankle", "heel", "metatars", "hoof", "ballfoot")):
        return "feet_toes"
    if any(w in n for w in (
        "head", "neck", "jaw", "skull", "snout", "nose", "mouth", "eye",
        "ear", "chin", "face", "tongue")):
        return "head_neck"
    if any(w in n for w in (
        "shoulder", "forearm", "upperarm", "lowerarm", "clavicle",
        "scapula", "elbow", "wrist", "hand", "finger", "humerus", "radius",
        "ulna", "foreleg", "frontleg")):
        return "forelimbs"
    if any(w in n for w in (
        "thigh", "shin", "calf", "knee", "femur", "tibia", "fibula",
        "hindleg", "backleg", "upperleg", "lowerleg", "hock")):
        return "hindlimbs"
    if any(w in n for w in (
        "pelvis", "root", "spine", "chest", "torso", "body", "hip",
        "abdomen", "belly", "rib", "breast")):
        return "torso_root"
    return "unclassified"


def _sha(path):
    h = hashlib.sha256()
    with pathlib.Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1048576), b""):
            h.update(chunk)
    return h.hexdigest()


def _validate(array, shape, label):
    a = np.asarray(array, dtype=np.float64)
    if a.shape != shape or not np.isfinite(a).all():
        raise ValueError(f"{label}: expected finite {shape} array, got {a.shape}")
    return a


def _stats(values):
    x = np.asarray(values, dtype=np.float64).reshape(-1)
    if not len(x) or not np.isfinite(x).all():
        raise ValueError("empty/nonfinite ground-truth error array")
    return {
        "mean": round(float(x.mean()), 5),
        "median": round(float(np.median(x)), 5),
        "p95": round(float(np.percentile(x, 95)), 5),
        "max": round(float(x.max()), 5),
    }


def _groups(names, overrides=None):
    if overrides is None:
        overrides = {}
    if not isinstance(overrides, dict) or any(
            name not in names or group not in GROUPS
            for name, group in overrides.items()):
        raise ValueError("group overrides must map exact existing joint names to valid groups")
    labels = [overrides.get(name, classify_joint(name)) for name in names]
    members = {g: np.asarray([i for i, v in enumerate(labels) if v == g],
                              dtype=np.intp) for g in GROUPS}
    return labels, members


def evaluate(truth, rig, candidates, *, group_overrides=None):
    """Pure NumPy core; returns report + CSV rows without filesystem effects.

    candidates: {variant_label: parsed motion.json}. Accuracy from Blender
    joint truth is independent of each variant's Solver Reader observations.
    """
    if not isinstance(truth, dict) or not isinstance(rig, dict):
        raise ValueError("Blender truth and rig must be objects")
    names = [k["name"] for k in rig["keypoints"]]
    bones = [b["name"] for b in rig["bones"]]
    if not names or len(names) != len(set(names)) or len(bones) != len(set(bones)):
        raise ValueError("invalid or duplicate rig joint/bone names")
    if truth.get("names") != names:
        raise ValueError("Blender truth joint names/order differ from rig keypoints")
    fps = float(truth.get("fps", 0))
    if not np.isfinite(fps) or fps <= 0:
        raise ValueError("Blender truth FPS must be positive finite")
    raw_truth = np.asarray(truth.get("joints"), dtype=np.float64)
    if raw_truth.ndim != 3 or raw_truth.shape[1:] != (len(names), 3):
        raise ValueError("invalid Blender ground-truth (T,J,3) shape")
    T = len(raw_truth)
    if T < 3 or not np.isfinite(raw_truth).all():
        raise ValueError("Blender truth needs >=3 finite motion frames")
    if not isinstance(candidates, dict) or not candidates:
        raise ValueError("at least one candidate Motion is required")
    if len(set(candidates)) != len(candidates):
        raise ValueError("duplicate Motion variant labels")
    labels, members = _groups(names, group_overrides)
    root_name = rig["bones"][0].get("head_joint")
    if root_name not in names:
        raise ValueError("root bone head_joint is not a ground-truth keypoint")
    root_idx = names.index(root_name)
    out = {
        "schema_version": PROFILE,
        "reference": "Blender evaluated armature keypoint world positions, NOT the fitted Solver joints",
        "truth_type": "controlled_synthetic_animation",
        "fps": fps, "frames": T,
        "keypoints": len(names), "bones": len(bones),
        "root_keypoint": root_name,
        "group_counts": {g: int(len(ids)) for g, ids in members.items()},
        "unclassified_joint_names": [n for n, lab in zip(names, labels)
                                     if lab == "unclassified"],
        "variants": {},
        "caveat": ("This measures 3D reconstruction error against a Blender-controlled "
                   "synthetic animated rig. It does not certify natural behavior "
                   "or H3Max video multi-view synchronization."),
    }
    joint_rows, frame_rows = [], []
    for tag, motion in candidates.items():
        if not tag or not isinstance(motion, dict):
            raise ValueError("invalid variant label/motion")
        if motion.get("joint_names") != names or motion.get("bones") != bones:
            raise ValueError(f"{tag}: Motion joint/bone ordering differs from truth rig")
        rate = float(motion.get("fps", 0))
        if not np.isfinite(rate) or abs(rate-fps) > 1e-5:
            raise ValueError(f"{tag}: Motion FPS mismatch")
        pred = _validate(motion.get("joints"), (T, len(names), 3), tag+" joints")
        _validate(motion.get("trans"), (T, 3), tag+" Root translation")
        _validate(motion.get("root_quat"), (T, 4), tag+" Root quaternion")
        delta_cm = np.linalg.norm(pred - raw_truth, axis=-1) * 100.
        truth_speed = np.diff(raw_truth, axis=0) * fps
        pred_speed = np.diff(pred, axis=0) * fps
        velocity_error_cm_s = np.linalg.norm(pred_speed-truth_speed, axis=-1)*100.
        truth_acc = np.diff(raw_truth, axis=0, n=2) * fps**2
        pred_acc = np.diff(pred, axis=0, n=2) * fps**2
        accel_error_cm_s2 = np.linalg.norm(pred_acc-truth_acc, axis=-1)*100.
        report = {
            "position_error_cm": _stats(delta_cm),
            "velocity_error_cm_s": _stats(velocity_error_cm_s),
            "acceleration_error_cm_s2": _stats(accel_error_cm_s2),
            "root_world_keypoint_position_error_cm": _stats(delta_cm[:, root_idx]),
            "root_world_keypoint_velocity_error_cm_s": _stats(velocity_error_cm_s[:, root_idx]),
            "per_group": {},
            "worst_mean_error_joints": [],
        }
        for group, ids in members.items():
            if not len(ids):
                report["per_group"][group] = None
                continue
            report["per_group"][group] = {
                "joints": len(ids),
                "position_error_cm": _stats(delta_cm[:, ids]),
                "velocity_error_cm_s": _stats(velocity_error_cm_s[:, ids]),
                "acceleration_error_cm_s2": _stats(accel_error_cm_s2[:, ids]),
            }
        for j, name in enumerate(names):
            summary = _stats(delta_cm[:, j])
            worst_frame = int(np.argmax(delta_cm[:, j]))
            joint_rows.append({
                "variant": tag, "joint": name, "group": labels[j],
                "mean_cm": summary["mean"], "median_cm": summary["median"],
                "p95_cm": summary["p95"], "max_cm": summary["max"],
                "worst_frame": worst_frame,
                "velocity_error_mean_cm_s": _stats(velocity_error_cm_s[:, j])["mean"],
                "acceleration_error_mean_cm_s2": _stats(accel_error_cm_s2[:, j])["mean"],
            })
        worst = np.argsort(-delta_cm.mean(axis=0), kind="stable")[:12]
        report["worst_mean_error_joints"] = [
            {"joint": names[int(i)], "group": labels[int(i)],
             "mean_cm": float(np.round(delta_cm[:, i].mean(), 5)),
             "max_cm": float(np.round(delta_cm[:, i].max(), 5)),
             "worst_frame": int(np.argmax(delta_cm[:, i]))}
            for i in worst
        ]
        for t in range(T):
            row = {"variant": tag, "frame": t,
                   "seconds": round(t/fps, 6),
                   "mean_cm": round(float(delta_cm[t].mean()), 5),
                   "p95_cm": round(float(np.percentile(delta_cm[t], 95)), 5),
                   "max_cm": round(float(delta_cm[t].max()), 5),
                   "root_world_error_cm": round(float(delta_cm[t, root_idx]), 5)}
            for group, ids in members.items():
                row[group+"_mean_cm"] = (None if not len(ids)
                                        else round(float(delta_cm[t, ids].mean()), 5))
            frame_rows.append(row)
        out["variants"][tag] = report
    return out, joint_rows, frame_rows


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("truth", help="ground_truth/gt_render/joints.json from Blender")
    parser.add_argument("rig_info", help="exact assets/dino/rigged/rig_info.json")
    parser.add_argument("out_dir", help="NEW output directory; refuses overwrite")
    parser.add_argument("--variant", action="append", required=True,
                        help="one label=motion.json per candidate (repeatable)")
    parser.add_argument("--group-overrides", help="optional JSON {exact_joint_name: group}")
    parser.add_argument("--source-motion", help="original procedural animation; provenance metadata only")
    args = parser.parse_args(argv)
    output = pathlib.Path(args.out_dir).resolve()
    if output.exists():
        raise FileExistsError("full-body QA directory already exists: "+str(output))
    paths = {}
    for entry in args.variant:
        label,sep,path = entry.partition("=")
        if not sep or not label.isidentifier() or label in paths:
            raise ValueError("--variant must contain unique identifier=filename entries")
        paths[label] = pathlib.Path(path)
    for path in [pathlib.Path(args.truth),pathlib.Path(args.rig_info),*paths.values()]:
        if not path.is_file():
            raise FileNotFoundError(path)
    truth = json.loads(pathlib.Path(args.truth).read_text(encoding="utf-8"))
    rig = json.loads(pathlib.Path(args.rig_info).read_text(encoding="utf-8"))
    candidates = {key:json.loads(path.read_text(encoding="utf-8"))
                  for key,path in paths.items()}
    overrides = (json.loads(pathlib.Path(args.group_overrides).read_text(encoding="utf-8"))
                 if args.group_overrides else None)
    report, by_joint, by_frame = evaluate(truth, rig, candidates,
                                          group_overrides=overrides)
    report["input_sha256"] = {
        "blender_truth": _sha(args.truth),
        "rig_info": _sha(args.rig_info),
        "motions": {key: _sha(path) for key,path in paths.items()},
    }
    if args.source_motion:
        p = pathlib.Path(args.source_motion)
        source = json.loads(p.read_text(encoding="utf-8"))
        if (source.get("bones") != [b["name"] for b in rig["bones"]] or
                abs(float(source.get("fps", 0))-report["fps"])>1e-5 or
                len(source.get("euler", [])) != report["frames"]):
            raise ValueError("procedural source motion contract differs from Blender truth")
        report["input_sha256"]["source_motion"] = _sha(p)
    output.mkdir(parents=True, exist_ok=False)
    (output/"full_body_report.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False),encoding="utf-8")
    def write_csv(filename, rows):
        with (output/filename).open("w",newline="",encoding="utf-8") as fd:
            writer = csv.DictWriter(fd, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)
    write_csv("by_joint.csv",by_joint)
    write_csv("by_frame.csv",by_frame)
    print(json.dumps({
        "status": "evaluated_against_blender_joint_truth",
        "frames": report["frames"], "keypoints": report["keypoints"],
        "group_counts": report["group_counts"],
        "unclassified_joint_names": report["unclassified_joint_names"],
        "variant_mean_3d_error_cm": {
            k: v["position_error_cm"]["mean"] for k,v in report["variants"].items()},
        "report": str(output/"full_body_report.json"),
        "by_joint": str(output/"by_joint.csv"),
        "by_frame": str(output/"by_frame.csv"),
    }, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
